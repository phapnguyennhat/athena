// Needs Postgres, Redis and RabbitMQ from docker-compose.yml, migrated (`pnpm migration:run`).
import { randomUUID } from 'node:crypto';
import { Test } from '@nestjs/testing';
import type { INestApplication } from '@nestjs/common';
import { Transport, type MicroserviceOptions } from '@nestjs/microservices';
import { ThrottlerGuard } from '@nestjs/throttler';
import { DataSource } from 'typeorm';
import request from 'supertest';
import type { App } from 'supertest/types.js';
import { AppModule } from '../src/app.module.js';
import { aiJobsConsumerOptions } from '../src/modules/ai-jobs/ai-jobs.constants.js';
import { PathConversation } from '../src/modules/learning-paths/entities/path-conversation.entity.js';
import { PathAi } from '../src/modules/learning-paths/path-ai.js';
import type { LessonInput, LessonOutput } from '../src/modules/lessons/lesson-output.js';
import { StreakService } from '../src/modules/lessons/streak.service.js';
import { User } from '../src/modules/users/user.entity.js';
import { FakePathAi } from './fake-path-ai.js';

class CountingAi extends FakePathAi {
  lessonCalls = 0;
  override async lesson(input: LessonInput): Promise<LessonOutput> {
    this.lessonCalls++;
    return super.lesson(input);
  }
}

describe('Lessons, quizzes, progress and streak (e2e)', () => {
  let app: INestApplication<App>;
  let http: ReturnType<typeof request>;
  let ds: DataSource;
  const ai = new CountingAi();

  beforeAll(async () => {
    const moduleRef = await Test.createTestingModule({ imports: [AppModule] })
      .overrideGuard(ThrottlerGuard)
      .useValue({ canActivate: () => true })
      .overrideProvider(PathAi)
      .useValue(ai)
      .compile();
    app = moduleRef.createNestApplication();
    app.connectMicroservice<MicroserviceOptions>(
      { transport: Transport.RMQ, options: aiJobsConsumerOptions(process.env.RABBITMQ_URL!) },
      { inheritAppConfig: true },
    );
    await app.startAllMicroservices();
    await app.init();
    http = request(app.getHttpServer());
    ds = app.get(DataSource);
  });

  afterAll(() => app.close());

  async function newUser(timezone = 'Asia/Ho_Chi_Minh') {
    const email = `lesson-${randomUUID()}@example.com`;
    const password = 'correct horse battery';
    await http
      .post('/auth/sign-up')
      .send({ email, password, dateOfBirth: '2000-01-01', fullName: 'Test', timezone })
      .expect(202);
    await ds.getRepository(User).update({ email }, { emailVerifiedAt: new Date() });
    const { body } = await http.post('/auth/sign-in').send({ email, password }).expect(200);
    const auth = { Authorization: `Bearer ${body.accessToken}` };
    const userId = (await ds.getRepository(User).findOneByOrFail({ email })).id;
    const get = (url: string) => http.get(url).set(auth);
    const post = (url: string, body?: object) => http.post(url).set(auth).send(body);
    const settle = async (jobId: string) => {
      const until = Date.now() + 5000;
      for (;;) {
        const { body: job } = await get(`/jobs/${jobId}`).expect(200);
        if (job.status === 'succeeded' || job.status === 'failed') return job;
        if (Date.now() > until) throw new Error(`job ${jobId} still ${job.status}`);
        await new Promise((r) => setTimeout(r, 100));
      }
    };
    /** An active path generated by the fake AI. */
    const activePath = async () => {
      const { id } = (await post('/learning-paths/conversations').expect(201)).body;
      await ds
        .getRepository(PathConversation)
        .update(id, { ready: true, preferences: { topic: 'SQL', level: 'beginner' } });
      const job = await settle((await post(`/learning-paths/conversations/${id}/generate`).expect(202)).body.id);
      expect(job).toMatchObject({ status: 'succeeded' });
      await post(`/learning-paths/${job.resultId}/start`, {}).expect(200);
      return (await get(`/learning-paths/${job.resultId}`).expect(200)).body;
    };
    return { userId, auth, get, post, del: (url: string) => http.delete(url).set(auth), settle, activePath };
  }

  it('studies a lesson end to end: content once, quiz without key, graded attempt, completion, streak, dashboard', async () => {
    const u = await newUser();
    const path = await u.activePath();
    expect(path.progress).toEqual({ done: 0, total: 12 });
    const [first, second] = path.modules[0].lessons;
    expect(first).toEqual({ id: expect.any(String), title: expect.any(String), status: 'not_started' });

    // Opening marks it in progress; no content yet.
    let lesson = (await u.get(`/lessons/${first.id}`).expect(200)).body;
    expect(lesson).toMatchObject({
      status: 'in_progress',
      content: null,
      contentJob: null,
      previous: null,
      next: { id: second.id },
      videos: [],
      quiz: null,
    });

    const calls = ai.lessonCalls;
    const job = await u.settle((await u.post(`/lessons/${first.id}/generate-content`).expect(202)).body.id);
    expect(job).toMatchObject({ type: 'generate_lesson', status: 'succeeded', resultId: first.id });
    lesson = (await u.get(`/lessons/${first.id}`).expect(200)).body;
    expect(lesson.content.sections).toHaveLength(2);
    expect(lesson.searchQuery).toContain('hướng dẫn');
    // Stored content is reused: a second generate succeeds without another model call.
    await u.settle((await u.post(`/lessons/${first.id}/generate-content`).expect(202)).body.id);
    expect(ai.lessonCalls).toBe(calls + 1);

    // Quiz: none before generating, then 5 questions without the answer key.
    await u.get(`/lessons/${first.id}/quiz`).expect(404);
    await u.settle((await u.post(`/lessons/${first.id}/quiz/generate`).expect(202)).body.id);
    const quiz = (await u.get(`/lessons/${first.id}/quiz`).expect(200)).body;
    expect(quiz.questions).toHaveLength(5);
    expect(JSON.stringify(quiz)).not.toMatch(/answer|explanation/);

    await u.post(`/quizzes/${quiz.id}/attempts`, { answers: [1, 1] }).expect(400);
    const attempt = (await u.post(`/quizzes/${quiz.id}/attempts`, { answers: [1, 1, 1, 0, 2] }).expect(201)).body;
    expect(attempt).toMatchObject({ correct: 3, total: 5, streak: { current: 1, learnedToday: true } });
    expect(attempt.results[3]).toEqual({ selected: 0, answer: 1, correct: false, explanation: expect.any(String) });
    // A retry is a new attempt; the first is kept.
    await u.post(`/quizzes/${quiz.id}/attempts`, { answers: [1, 1, 1, 1, 1] }).expect(201);
    expect((await u.get(`/lessons/${first.id}/quiz`).expect(200)).body).toMatchObject({
      attempts: 2,
      best: { correct: 5, total: 5 },
    });

    // Completion: idempotent, same-day actions don't grow the streak.
    const done = (await u.post(`/lessons/${first.id}/complete`).expect(200)).body;
    expect(done).toMatchObject({ status: 'completed', pathProgress: { done: 1, total: 12 }, streak: { current: 1 } });
    await u.post(`/lessons/${first.id}/complete`).expect(200);
    const [{ count }] = await ds.query(`SELECT count FROM daily_activity WHERE user_id = $1`, [u.userId]);
    expect(count).toBe(3); // two quiz attempts + one completion
    expect((await u.get(`/lessons/${first.id}`).expect(200)).body.status).toBe('completed');

    // Dashboard: continue with the next lesson; list shows progress.
    const dash = (await u.get('/dashboard').expect(200)).body;
    expect(dash).toMatchObject({
      streak: { current: 1, longest: 1, learnedToday: true },
      continue: { lessonId: second.id, pathId: path.id, done: 1, total: 12 },
      totals: { completedLessons: 1, quizAttempts: 2, paths: 1 },
    });
    expect(dash.streak.week.filter(Boolean)).toHaveLength(1);
    expect((await u.get('/learning-paths').expect(200)).body).toEqual([
      expect.objectContaining({ id: path.id, done: 1, total: 12, next: { id: second.id, title: second.title } }),
    ]);
  });

  it('keeps lessons private and deletes a path without losing learning days', async () => {
    const owner = await newUser();
    const other = await newUser();
    const path = await owner.activePath();
    const lessonId = path.modules[0].lessons[0].id;
    await other.get(`/lessons/${lessonId}`).expect(404);
    await other.post(`/lessons/${lessonId}/complete`).expect(404);
    await other.del(`/learning-paths/${path.id}`).expect(404);

    await owner.post(`/lessons/${lessonId}/complete`).expect(200);
    await owner.del(`/learning-paths/${path.id}`).expect(204);
    await owner.get(`/lessons/${lessonId}`).expect(404);
    expect((await owner.get('/learning-paths').expect(200)).body).toEqual([]);
    expect((await owner.get('/dashboard').expect(200)).body).toMatchObject({ streak: { current: 1 }, continue: null });
  });

  /** Rows still hanging off these content ids: the content itself, its videos, quiz and quiz attempts. */
  const leftovers = async (contentIds: string[]) =>
    (
      await ds.query(
        `SELECT (SELECT count(*) FROM lesson_contents WHERE id = ANY($1))::int AS contents,
                (SELECT count(*) FROM lesson_resources WHERE content_id = ANY($1))::int AS resources,
                (SELECT count(*) FROM quizzes WHERE content_id = ANY($1))::int AS quizzes,
                (SELECT count(*) FROM quiz_attempts a JOIN quizzes q ON q.id = a.quiz_id WHERE q.content_id = ANY($1))::int AS attempts`,
        [contentIds],
      )
    )[0];
  const contentIdsOfPath = async (pathId: string): Promise<string[]> =>
    (
      await ds.query(
        `SELECT l.content_id FROM path_lessons l JOIN path_modules m ON m.id = l.module_id WHERE m.path_id = $1`,
        [pathId],
      )
    ).map((r: { content_id: string }) => r.content_id);

  it('deletes a draft with its lesson content, videos, quiz and attempts', async () => {
    const u = await newUser();
    const path = await u.activePath();
    const lessonId = path.modules[0].lessons[0].id;
    await u.settle((await u.post(`/lessons/${lessonId}/generate-content`).expect(202)).body.id);
    await u.settle((await u.post(`/lessons/${lessonId}/quiz/generate`).expect(202)).body.id);
    const quiz = (await u.get(`/lessons/${lessonId}/quiz`).expect(200)).body;
    await u.post(`/quizzes/${quiz.id}/attempts`, { answers: [1, 1, 1, 1, 1] }).expect(201);
    const contentIds = await contentIdsOfPath(path.id);
    // A stored video, whether or not YouTube search is configured here.
    await ds.query(
      `INSERT INTO lesson_resources (content_id, provider, external_id, title, position)
       SELECT content_id, 'youtube', 'e2e-video', 'Video', 99 FROM path_lessons WHERE id = $1`,
      [lessonId],
    );
    const before = await leftovers(contentIds);
    expect(before).toMatchObject({ contents: 12, quizzes: 1, attempts: 1 });
    expect(before.resources).toBeGreaterThan(0);
    expect((await u.get('/dashboard').expect(200)).body.totals.quizAttempts).toBe(1);

    // An active original would only be hidden (copy-and-hide.e2e-spec.ts); a draft is deleted for real.
    await ds.query(`UPDATE learning_paths SET status = 'draft' WHERE id = $1`, [path.id]);
    await u.del(`/learning-paths/${path.id}`).expect(204);
    expect(await leftovers(contentIds)).toEqual({ contents: 0, resources: 0, quizzes: 0, attempts: 0 });
    expect((await u.get('/dashboard').expect(200)).body.totals.quizAttempts).toBe(0);
  });

  it("drops the replaced lessons' content when a draft is started with edited modules", async () => {
    const u = await newUser();
    const { id } = (await u.post('/learning-paths/conversations').expect(201)).body;
    await ds
      .getRepository(PathConversation)
      .update(id, { ready: true, preferences: { topic: 'Go', level: 'beginner' } });
    const job = await u.settle((await u.post(`/learning-paths/conversations/${id}/generate`).expect(202)).body.id);
    const draft = (await u.get(`/learning-paths/${job.resultId}`).expect(200)).body;
    await u.settle((await u.post(`/lessons/${draft.modules[0].lessons[0].id}/generate-content`).expect(202)).body.id);
    const oldIds = await contentIdsOfPath(draft.id);

    await u
      .post(`/learning-paths/${draft.id}/start`, {
        modules: [{ title: 'Một chương', lessons: [{ title: 'Một bài' }] }],
      })
      .expect(200);
    expect(await leftovers(oldIds)).toMatchObject({ contents: 0 });
    const newIds = await contentIdsOfPath(draft.id);
    expect(newIds).toHaveLength(1);
    expect(await leftovers(newIds)).toMatchObject({ contents: 1 });
  });

  it('refuses a quiz before content, and completion of a draft', async () => {
    const u = await newUser();
    const { id } = (await u.post('/learning-paths/conversations').expect(201)).body;
    await ds
      .getRepository(PathConversation)
      .update(id, { ready: true, preferences: { topic: 'Go', level: 'beginner' } });
    const job = await u.settle((await u.post(`/learning-paths/conversations/${id}/generate`).expect(202)).body.id);
    const draft = (await u.get(`/learning-paths/${job.resultId}`).expect(200)).body;
    const lessonId = draft.modules[0].lessons[0].id;
    expect((await u.post(`/lessons/${lessonId}/quiz/generate`).expect(409)).body.code).toBe('LESSON_NOT_READY');
    expect((await u.post(`/lessons/${lessonId}/complete`).expect(409)).body.code).toBe('PATH_NOT_STARTED');
  });

  it('PATCH /auth/me accepts only IANA timezones', async () => {
    const u = await newUser();
    await http.patch('/auth/me').set(u.auth).send({ timezone: 'Mars/Olympus' }).expect(400);
    const { body } = await http.patch('/auth/me').set(u.auth).send({ timezone: 'Europe/Paris' }).expect(200);
    expect(body.timezone).toBe('Europe/Paris');
  });

  describe('streak rules (Asia/Ho_Chi_Minh = UTC+7)', () => {
    const at = (iso: string) => new Date(iso);
    let streak: StreakService;
    beforeAll(() => {
      streak = app.get(StreakService);
    });
    const record = (userId: string, when: string) => ds.transaction((m) => streak.record(m, userId, at(when)));
    const stats = async (userId: string) =>
      ds
        .getRepository(User)
        .findOneByOrFail({ id: userId })
        .then((x) => ({ current: x.currentStreak, longest: x.longestStreak, last: x.lastActivityDate }));

    it('first day, same day, local midnight, missed day, timezone change', async () => {
      const { userId } = await newUser();
      expect(await record(userId, '2026-01-10T03:00:00Z')).toEqual({ date: '2026-01-10', newDay: true });
      expect(await stats(userId)).toEqual({ current: 1, longest: 1, last: '2026-01-10' });
      // 22:00 local, same day.
      expect(await record(userId, '2026-01-10T15:00:00Z')).toEqual({ date: '2026-01-10', newDay: false });
      // 17:30Z is 00:30 the next local day, though still Jan 10 in UTC.
      expect(await record(userId, '2026-01-10T17:30:00Z')).toEqual({ date: '2026-01-11', newDay: true });
      expect(await stats(userId)).toEqual({ current: 2, longest: 2, last: '2026-01-11' });
      // Jan 12 missed.
      await record(userId, '2026-01-13T03:00:00Z');
      expect(await stats(userId)).toEqual({ current: 1, longest: 2, last: '2026-01-13' });
      // Moving west: 03:00Z on Jan 14 is still Jan 13 in Los Angeles: no new day, history untouched.
      await ds.getRepository(User).update(userId, { timezone: 'America/Los_Angeles' });
      expect(await record(userId, '2026-01-14T03:00:00Z')).toEqual({ date: '2026-01-13', newDay: false });
      await record(userId, '2026-01-14T20:00:00Z');
      expect(await stats(userId)).toEqual({ current: 2, longest: 2, last: '2026-01-14' });
      const days = await ds.query(
        `SELECT to_char(activity_date, 'YYYY-MM-DD') AS d FROM daily_activity WHERE user_id = $1 ORDER BY 1`,
        [userId],
      );
      expect(days.map((r: { d: string }) => r.d)).toEqual(['2026-01-10', '2026-01-11', '2026-01-13', '2026-01-14']);
    });

    it('concurrent and retried actions count one day', async () => {
      const { userId } = await newUser();
      await Promise.all(Array.from({ length: 5 }, () => record(userId, '2026-02-01T05:00:00Z')));
      expect(await stats(userId)).toEqual({ current: 1, longest: 1, last: '2026-02-01' });
      const [{ count }] = await ds.query(`SELECT count FROM daily_activity WHERE user_id = $1`, [userId]);
      expect(count).toBe(5);
    });

    it('view reads a broken streak as 0 and fills the Mon–Sun week', async () => {
      const { userId } = await newUser();
      await record(userId, '2026-11-16T03:00:00Z'); // Monday
      await record(userId, '2026-11-17T03:00:00Z'); // Tuesday
      expect(await streak.view(userId, at('2026-11-18T03:00:00Z'))).toEqual({
        current: 2,
        longest: 2,
        learnedToday: false,
        today: '2026-11-18',
        week: [true, true, false, false, false, false, false],
      });
      expect((await streak.view(userId, at('2026-11-20T03:00:00Z'))).current).toBe(0);
    });
  });
});
